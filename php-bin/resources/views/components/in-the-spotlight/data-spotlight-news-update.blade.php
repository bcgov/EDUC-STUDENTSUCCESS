<!-- Vanilla JS for the news carousel -->
<script>
    document.addEventListener("DOMContentLoaded", function() {
        let currentNewsSlide = 0;
        const newsSlides = document.querySelectorAll('#dataSpotlightNewsUpdate .news-carousel-slide');
        const newsIndicators = document.querySelectorAll('#dataSpotlightNewsUpdate .news-indicators button');
        const totalNewsSlides = newsSlides.length;

        window.newsGoToSlide = function(target) {
            if(totalNewsSlides === 0) return;
            
            // Remove active class from current
            newsSlides[currentNewsSlide].classList.remove('active');
            newsIndicators[currentNewsSlide].classList.remove('active');
            
            // Update current index
            if (target === 'prev') {
                currentNewsSlide = (currentNewsSlide - 1 + totalNewsSlides) % totalNewsSlides;
            } else if (target === 'next') {
                currentNewsSlide = (currentNewsSlide + 1) % totalNewsSlides;
            } else {
                currentNewsSlide = target;
            }
            
            // Add active class to new
            newsSlides[currentNewsSlide].classList.add('active');
            newsIndicators[currentNewsSlide].classList.add('active');
        };
    });
</script>
